pub fn all() -> Vec<Language> {
    LANGUAGES.iter().map(|(c, n)| Language { code: c, name: n }).collect()
}

pub fn name_of(code: &str) -> Option<&'static str> {
    LANGUAGES.iter().find(|(c, _)| *c == code).map(|(_, n)| *n)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn all_codes_known_to_whisper() {
        assert_eq!(LANGUAGES.len(), 100);
        assert_eq!(LANGUAGES[0].0, "ru");
        for (code, _) in LANGUAGES {
            assert!(whisper_rs::get_lang_id(code).is_some(), "unknown code {code}");
        }
        let mut codes: Vec<_> = LANGUAGES.iter().map(|l| l.0).collect();
        codes.sort();
        codes.dedup();
        assert_eq!(codes.len(), LANGUAGES.len());
    }
}
